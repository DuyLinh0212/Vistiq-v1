import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.VISTIQ_PLAYWRIGHT_MODULE ?? 'playwright');
const browser = await chromium.launch({ headless: true, args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', '--autoplay-policy=no-user-gesture-required','--no-proxy-server'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
await context.route('**/*', route => ['127.0.0.1','localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
await context.grantPermissions(['microphone'], { origin: 'http://127.0.0.1:9001' });
await context.grantPermissions(['microphone'], { origin: 'http://127.0.0.1:9000' });
const page = await context.newPage();
console.log('Browser launched');
page.setDefaultNavigationTimeout(60000);
page.setDefaultTimeout(60000);
const errors = [];
const activeRequests = new Set();
page.on('request', request => activeRequests.add(request.url()));
page.on('requestfinished', request => activeRequests.delete(request.url()));
page.on('requestfailed', request => activeRequests.delete(request.url()));
page.on('pageerror', error => errors.push(error.message));
page.on('dialog', dialog => dialog.accept());
const settlePage = async () => {
    try { await page.waitForLoadState('networkidle', { timeout: 10000 }); }
    catch (error) { if (activeRequests.size) { throw error; } }
    await page.waitForFunction(() => document.readyState === 'complete');
};
try {
    await page.goto('http://127.0.0.1:9001/login', { waitUntil: 'domcontentloaded' });
    await settlePage();
    console.log('Admin login controls:', await page.locator('form').innerText());
    assert.ok((await page.locator('#admin-email').boundingBox()).width > 300);
    await page.getByRole('button', { name: 'Hiện mật khẩu' }).click();
    assert.equal(await page.locator('#admin-password').getAttribute('type'), 'text');
    await page.getByRole('button', { name: 'Ẩn mật khẩu' }).click();
    await page.screenshot({ path: 'storage/browser-admin-login-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({ path: 'storage/browser-admin-login-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByLabel('Email quản trị').fill('admin@acceptance.invalid');
    await page.getByLabel('Mật khẩu', { exact: true }).fill('Acceptance-only-2026!');
    await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
    await page.waitForURL('**/admin');
    await page.goto('http://127.0.0.1:9001/admin/questions/create');
    await settlePage();
    assert.equal(await page.locator('.tiptap').count(), 2);
    await page.locator('[data-editor-exam]').selectOption({ label: 'IELTS' });
    await page.locator('[data-editor-skill]').selectOption('speaking');
    assert.equal(await page.locator('[data-question-type] option:checked').getAttribute('data-code'), 'speaking');
    await page.screenshot({ path: 'storage/browser-question-editor.png', fullPage: true });
    await page.goto('http://127.0.0.1:9001/admin/exams/create');
    await settlePage();
    await page.locator('[data-wizard-step="1"]').click();
    await page.locator('[data-add-section]').click();
    assert.equal(await page.locator('[data-section-index]').count(), 1);
    await page.screenshot({ path: 'storage/browser-exam-builder.png', fullPage: true });
    await page.goto('http://127.0.0.1:9001/admin/exams/1/preview');
    await settlePage();
    assert.equal(await page.locator('[data-record]').count(), 1);
    await page.locator('[data-viewport]').selectOption('mobile');
    assert.equal(await page.locator('[data-exam-runner]').getAttribute('data-viewport'), 'mobile');
    await page.locator('[data-play-audio]').click();
    await page.waitForFunction(() => [...document.querySelectorAll('.assessment-audio audio')].some(audio => audio.currentTime > 0));
    await page.locator('[data-record]').click();
    await page.waitForFunction(() => document.querySelector('[data-record]')?.textContent === 'Dừng ghi âm');
    await page.waitForTimeout(1200);
    await page.locator('[data-record]').click();
    await page.waitForFunction(() => document.querySelector('[data-recording]')?.src.startsWith('blob:'));
    await page.screenshot({ path: 'storage/browser-preview-mobile.png', fullPage: true });
    await page.goto('http://127.0.0.1:9000/login');
    await settlePage();
    console.log('Learner login controls:', await page.locator('form').first().innerText());
    await page.locator('input[name="email"]').fill('learner@acceptance.invalid');
    await page.locator('input[name="password"]').fill('Acceptance-only-2026!');
    await page.locator('form').first().locator('button[type="submit"]').click();
    await page.goto('http://127.0.0.1:9000/exams');
    await settlePage();
    await page.getByRole('button', { name: 'Bắt đầu' }).click();
    await page.waitForURL('**/attempts/*');
    await context.setOffline(true);
    await page.locator('[data-record]').click();
    await page.waitForFunction(() => document.querySelector('[data-record]')?.textContent === 'Dừng ghi âm');
    await page.waitForTimeout(1200);
    await page.locator('[data-record]').click();
    await page.waitForFunction(() => document.querySelector('[data-save-status]')?.textContent.includes('Recording đã lưu trên thiết bị'));
    const attemptUrl = page.url();
    await assert.rejects(page.reload({ waitUntil: 'domcontentloaded' }), /ERR_INTERNET_DISCONNECTED/);
    const upload = page.waitForResponse(response => response.url().endsWith('/recording'));
    await context.setOffline(false);
    await page.goto(attemptUrl);
    assert.equal((await upload).status(), 201);
    await page.waitForTimeout(3500);
    await page.reload();
    await page.waitForSelector('[data-record]');
    await page.waitForFunction(() => document.querySelector('[data-recording]')?.src.includes('/media/'));
    await page.screenshot({ path: 'storage/browser-learner-runner.png', fullPage: true });
    await page.locator('[data-submit]').click();
    await page.waitForURL('**/result');
    assert.ok((await page.locator('main').innerText()).includes('Đang chờ chấm'));
    await page.screenshot({ path: 'storage/browser-pending-result.png', fullPage: true });
    assert.deepEqual(errors, []);
    console.log('Browser acceptance passed: dynamic editor, Tiptap, builder, responsive preview, audio, simulated microphone, offline recording recovery, upload, reload, submit.');
} catch (error) {
    console.log('Pending browser requests:', [...activeRequests]);
    await page.screenshot({ path: 'storage/browser-failure.png', fullPage: true });
    throw error;
} finally { await browser.close(); }
